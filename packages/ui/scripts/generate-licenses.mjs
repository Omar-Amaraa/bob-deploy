import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageDirectory = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(await readFile(join(packageDirectory, 'package.json'), 'utf8'));
const packages = Object.keys(manifest.dependencies).filter((name) => !name.startsWith('@bob-deploy/'));
const entries = [];
for (const name of packages.sort()) {
  const dependencyManifest = JSON.parse(
    await readFile(join(packageDirectory, 'node_modules', name, 'package.json'), 'utf8'),
  );
  entries.push({ name, license: dependencyManifest.license ?? 'See package' });
}
const output = `// Generated by scripts/generate-licenses.mjs. Do not edit by hand.\nexport const thirdPartyLicenses = ${JSON.stringify(entries, null, 2)} as const;\n`;
await writeFile(join(packageDirectory, 'src', 'generated', 'licenses.ts'), output, 'utf8');
