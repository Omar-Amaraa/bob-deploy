#!/usr/bin/env bash
# 40-install-helpers.sh <admin_user>
# Finalizes helper installation: expects the helper scripts and allowlist.txt to already be
# present at /usr/local/lib/bob-deploy/bin/ (uploaded via SFTP by the TypeScript side before
# this script runs), locks down their permissions, grants the admin user passwordless sudo to run
# exactly those allowlisted binaries (nothing else), sets up the shared log directory, and marks
# the server as bootstrapped so 00-preflight.sh can detect a previous install.
#
# S7: 10-create-admin.sh grants the admin user a temporary, unscoped NOPASSWD:ALL sudoers entry
# (/etc/sudoers.d/90-bob-deploy-<admin_user>) so the bootstrap sequence itself can run privileged
# steps as that user before this, the last bootstrap step, exists. Once the scoped 91- file below
# is written and validated, this script removes that temporary grant and the admin user's "sudo"
# group membership entirely — after bootstrap, the admin user has no general sudo, only the exact
# bd-* helper paths below.
#
# Usage: 40-install-helpers.sh <admin_user>
# On success: BD_RESULT {"ok":true,"helperCount":"<n>"}
# On failure: BD_RESULT {"ok":false,"error":"<code>","message":"..."}
#
# @@LIB@@

require_root

ADMIN_USER="${1:-}"
if [ -z "$ADMIN_USER" ]; then
  die "Usage: 40-install-helpers.sh <admin_user>" "BD_BAD_ARGS"
fi
if ! validate_user "$ADMIN_USER"; then
  die "Invalid admin user name: ${ADMIN_USER}" "BD_INVALID_USER"
fi
if ! id "$ADMIN_USER" >/dev/null 2>&1; then
  die "User ${ADMIN_USER} does not exist; run 10-create-admin.sh first." "BD_USER_NOT_FOUND"
fi

HELPERS_DIR="/usr/local/lib/bob-deploy/bin"
ALLOWLIST="${HELPERS_DIR}/allowlist.txt"

if [ ! -d "$HELPERS_DIR" ]; then
  die "Helpers directory ${HELPERS_DIR} was not found; upload the helpers before running this script." "BD_HELPERS_MISSING"
fi
if [ ! -f "$ALLOWLIST" ]; then
  die "allowlist.txt was not found in ${HELPERS_DIR}." "BD_HELPERS_MISSING"
fi

HELPER_COUNT=0
while IFS= read -r path || [ -n "$path" ]; do
  [ -z "$path" ] && continue
  case "$path" in
    '#'*) continue ;;
  esac
  case "$path" in
    "${HELPERS_DIR}"/*) ;;
    *) die "allowlist.txt entry outside of ${HELPERS_DIR}: ${path}" "BD_ALLOWLIST_INVALID" ;;
  esac
  if [ ! -f "$path" ]; then
    die "allowlist.txt references a missing file: ${path}" "BD_ALLOWLIST_INVALID"
  fi
  chown root:root "$path"
  chmod 0755 "$path"
  HELPER_COUNT=$((HELPER_COUNT + 1))
done <"$ALLOWLIST"

if [ "$HELPER_COUNT" -eq 0 ]; then
  die "allowlist.txt contained no usable entries." "BD_ALLOWLIST_INVALID"
fi

chown root:root "$ALLOWLIST"
chmod 0644 "$ALLOWLIST"
chown -R root:root "$HELPERS_DIR"
find "$HELPERS_DIR" -maxdepth 1 -type d -exec chmod 0755 {} \;

# Passwordless sudo, scoped to exactly the allowlisted absolute paths — nothing else.
SUDOERS_FILE="/etc/sudoers.d/91-bob-deploy-helpers-${ADMIN_USER}"
{
  printf '# Managed by Bob Deploy. Regenerated by 40-install-helpers.sh.\n'
  while IFS= read -r path || [ -n "$path" ]; do
    [ -z "$path" ] && continue
    case "$path" in
      '#'*) continue ;;
    esac
    printf '%s ALL=(root) NOPASSWD: %s\n' "$ADMIN_USER" "$path"
  done <"$ALLOWLIST"
} >"$SUDOERS_FILE"
chmod 0440 "$SUDOERS_FILE"
if ! visudo -cf "$SUDOERS_FILE" >/dev/null 2>&1; then
  rm -f "$SUDOERS_FILE"
  die "Generated helpers sudoers file failed validation." "BD_SUDOERS_INVALID"
fi

mkdir -p "$BD_LOG_DIR"
chown root:"$ADMIN_USER" "$BD_LOG_DIR" 2>/dev/null || chown root:root "$BD_LOG_DIR"
chmod 0750 "$BD_LOG_DIR"
touch "$BD_LOG_FILE"
chmod 0640 "$BD_LOG_FILE"

# S7: the scoped 91- sudoers file above is validated and in place — revoke 10-create-admin.sh's
# temporary unscoped grant now, so the admin user is left with no general sudo at all.
rm -f "/etc/sudoers.d/90-bob-deploy-${ADMIN_USER}"
gpasswd -d "$ADMIN_USER" sudo >/dev/null 2>&1 || true

mkdir -p /etc/bob-deploy
date -u +'%Y-%m-%dT%H:%M:%SZ' >/etc/bob-deploy/bootstrapped

result helperCount "$HELPER_COUNT"
